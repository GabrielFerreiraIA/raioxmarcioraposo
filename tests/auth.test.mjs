import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { randomBytes, createHmac } from 'node:crypto';
import handler from '../api/site.mjs';

test('conteúdo reservado, sessão válida e rotas de publicação', async t => {
  process.env.RAIOX_PASSWORD = randomBytes(20).toString('hex');
  process.env.SESSION_SECRET = randomBytes(48).toString('hex');
  const server = createServer((req, res) => handler(req, res));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, options = {}) => fetch(base + path, { redirect: 'manual', ...options });
  const post = password => ({ method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ password }) });
  const locked = await request('/');
  const lockedText = await locked.text();
  assert.match(lockedText, /Senha de acesso/);
  assert.doesNotMatch(lockedText, /R\$ 45|rotatividade|Máquina de Recrutamento/);
  assert.match(locked.headers.get('cache-control'), /no-store/);
  for (const path of ['/styles.css', '/script.js', '/dist/index.html', '/.env.local', '/.private/evidencias.md', '/api/site?route=dist/index.html']) {
    const response = await request(path);
    assert.equal(response.status, 303, path);
    assert.equal(response.headers.get('location'), '/');
  }
  assert.equal((await request('/assets/multiplix-symbol.jpg')).status, 200);
  assert.equal((await request('/assets/multiplix-wordmark.jpg')).status, 200);
  assert.equal((await request('/login.css')).status, 200);
  const wrong = await request('/login', post('incorrect-password'));
  assert.equal(wrong.status, 401);
  assert.match(await wrong.text(), /Senha incorreta/);
  assert.equal((await request('/login', { ...post(process.env.RAIOX_PASSWORD), headers: { ...post('').headers, origin: 'https://outro-site.example' } })).status, 403);
  const login = await request('/login', post(process.env.RAIOX_PASSWORD));
  assert.equal(login.status, 303);
  const cookieHeader = login.headers.get('set-cookie');
  assert.match(cookieHeader, /HttpOnly/);
  assert.match(cookieHeader, /SameSite=Lax/);
  const cookie = cookieHeader.split(';')[0];
  const opened = await request('/', { headers: { cookie } });
  assert.equal(opened.status, 200);
  const content = await opened.text();
  assert.match(content, /R\$ 45–50 mi/);
  assert.match(content, /Máquina de Recrutamento/);
  assert.doesNotMatch(content, new RegExp(process.env.RAIOX_PASSWORD));
  assert.equal((await request('/styles.css', { headers: { cookie } })).status, 200);
  assert.equal((await request('/api/site?route=styles.css', { headers: { cookie } })).status, 200);
  assert.equal((await request('/api/site?route=', { headers: { cookie } })).status, 200);
  assert.equal((await request('/.env.local', { headers: { cookie } })).status, 404);
  assert.equal((await request('/dist/index.html', { headers: { cookie } })).status, 404);
  const forged = cookie.slice(0, -1) + (cookie.endsWith('A') ? 'B' : 'A');
  assert.match(await (await request('/', { headers: { cookie: forged } })).text(), /Senha de acesso/);
  const payload = `${Math.floor(Date.now() / 1000) - 1}.${randomBytes(16).toString('hex')}`;
  const signature = createHmac('sha256', process.env.SESSION_SECRET).update(`${process.env.RAIOX_PASSWORD}\0${payload}`).digest('base64url');
  assert.match(await (await request('/', { headers: { cookie: `multiplix_raiox=${payload}.${signature}` } })).text(), /Senha de acesso/);
  const logout = await request('/logout', { method: 'POST', headers: { cookie } });
  assert.match(logout.headers.get('set-cookie'), /Max-Age=0/);
  const oldSecret = process.env.SESSION_SECRET;
  delete process.env.SESSION_SECRET;
  assert.equal((await request('/')).status, 503);
  process.env.SESSION_SECRET = oldSecret;
});
